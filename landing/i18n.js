// Keep original text nodes so switching languages never loses markup or listeners.
const originalWebsiteText = new WeakMap();
const originalWebsiteAttributes = new WeakMap();
const supportedWebsiteLanguages = ['en', 'si', 'ta'];
let websiteLanguage = 'en';
function translateWebsiteElement(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement.closest('script, style, select, .brand, .scripts, .lang-chips, .lang-card .big')) continue;
    if (!originalWebsiteText.has(node)) originalWebsiteText.set(node, node.textContent);
    const source = originalWebsiteText.get(node);
    const key = source.trim();
    const translated = websiteLanguage === 'en' ? key : websiteTranslations[key]?.[websiteLanguage];
    if (translated) node.textContent = source.replace(key, translated);
    else node.textContent = source;
  }
  const elements = [root, ...root.querySelectorAll('[aria-label]')];
  elements.forEach((element) => {
    if (!element.hasAttribute('aria-label')) return;
    if (!originalWebsiteAttributes.has(element)) originalWebsiteAttributes.set(element, element.getAttribute('aria-label'));
    const source = originalWebsiteAttributes.get(element);
    element.setAttribute('aria-label', websiteLanguage === 'en' ? source : (websiteTranslations[source]?.[websiteLanguage] || source));
  });
}
